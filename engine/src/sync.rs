/// Border colors sourced by hyprland.conf; keeps `hyprctl reload` consistent
/// with the live `hyprctl keyword` pushes.
fn write_hypr_colors(pal: &Palette) -> Result<(), String> {
    let mut data = String::new();
    data.push_str("# oxocarbon-morph :: hyprland border palette (generated by `theme set`)\n");
    data.push_str("general {\n");
    data.push_str(&format!("    col.active_border = {}\n", pal.accent_rgba()));
    data.push_str(&format!("    col.inactive_border = {}\n", pal.border_rgba()));
    data.push_str("}\n");
    paths::atomic_write(&paths::hypr_colors(), &data)
        .map_err(|e| format!("hyprland-colors.conf: {}", e))
}

fn write_hyprlock_colors(pal: &Palette) -> Result<(), String> {
    let rgb = |c: &str| format!("rgb({})", c.trim_start_matches('#'));
    let data = format!(
        "# oxocarbon-morph :: hyprlock palette (generated)\n\
         $bg = {}\n\
         $surface = {}\n\
         $ink = {}\n\
         $muted = {}\n\
         $accent = {}\n\
         $accent_alt = {}\n\
         $border = {}\n",
        rgb(&pal.bg),
        rgb(&pal.surface),
        rgb(&pal.ink),
        rgb(&pal.muted),
        rgb(&pal.accent),
        rgb(&pal.accent_alt),
        rgb(&pal.border)
    );
    paths::atomic_write(&paths::hyprlock_colors(), &data)
        .map_err(|e| format!("hyprlock-colors.conf: {}", e))
}

