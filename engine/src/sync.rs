//! Atomic multi-target color sync + mpvpaper lifecycle (v1.0).
//!
//! Order matters: config files and icons land on disk first (atomic writes),
//! then live processes are signaled, then the wallpaper switches — via mpv
//! IPC `loadfile` when a live socket answers (<80ms, zero respawn), else via
//! the swaybg + mpvpaper boot flow. Frame generation never blocks a switch.

use crate::{cava, daemon, frames, hypr, icons, json, mpv, palette::Palette, paths};
use std::fs;
use std::process::{Child, Command, Stdio};
use std::thread;
use std::time::Duration;

pub struct SyncReport {
    /// true = switched via IPC loadfile on the live mpvpaper
    pub wallpaper_ipc: bool,
    /// true = mpvpaper (re)spawned through the swaybg boot flow
    pub wallpaper_started: bool,
    pub hyprland: bool,
    pub kitty_live: bool,
    /// number of palette-baked icons rendered
    pub icons: usize,
}

fn write_active_palette(pal: &Palette) -> Result<(), String> {
    let data = format!(
        "{{\n  \"name\": \"{}\",\n  \"bg\": \"{}\",\n  \"surface\": \"{}\",\n  \"ink\": \"{}\",\n  \"muted\": \"{}\",\n  \"accent\": \"{}\",\n  \"accent_alt\": \"{}\",\n  \"border\": \"{}\"\n}}\n",
        json::escape(&pal.name),
        json::escape(&pal.bg),
        json::escape(&pal.surface),
        json::escape(&pal.ink),
        json::escape(&pal.muted),
        json::escape(&pal.accent),
        json::escape(&pal.accent_alt),
        json::escape(&pal.border)
    );
    paths::atomic_write(&paths::active_palette_file(), &data)
        .map_err(|e| format!("active-palette.json: {}", e))
}

