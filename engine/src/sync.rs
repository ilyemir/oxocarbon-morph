fn live_kitty() -> bool {
    let conf = paths::kitty_conf();
    let run = |extra: &[&str]| -> bool {
        let mut cmd = Command::new("kitty");
        cmd.arg("@");
        for e in extra {
            cmd.arg(e);
        }
        cmd.args(["set-colors", "--all"])
            .arg(&conf)
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
    };
    // Preferred: shared abstract socket from kitty.conf listen_on.
    if run(&["--to", "unix:@oxocarbon-kitty"]) {
        return true;
    }
    // Fallback: KITTY_LISTEN_ON inherited from a kitty parent process.
    run(&[])
}

pub fn signal(process: &str, sig: &str) {
    let _ = Command::new("pkill")
        .arg(format!("-{}", sig))
        .arg(process)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
}

/// Light waybar refresh: re-runs custom modules with "signal": 8
/// (theme pill, shield) without a full bar reload.
pub fn waybar_rtmin() {
    let _ = Command::new("pkill")
        .arg("-RTMIN+8")
        .arg("waybar")
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
}

/// Boot flow: cached frame on screen instantly (swaybg), mpvpaper spawning
/// underneath, swaybg dropped once the mpv IPC socket answers.
fn respawn_wallpaper(wall: &str) -> Result<bool, String> {
    // replace any running instance (incl. pre-v1.0 sockets) + stale sockets
    let _ = Command::new("pkill")
        .args(["-x", "mpvpaper"])
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
    let _ = fs::remove_file(paths::MPV_SOCKET);
    let _ = fs::remove_file(paths::MPV_SOCKET_LEGACY);

    frames::ensure(wall);
    let frame = paths::frame_path(wall);
    let mut swaybg: Option<Child> = None;
    if frame.exists() {
        swaybg = Command::new("swaybg")
            .args(["-o", "*", "-i"])
            .arg(&frame)
            .args(["-m", "fill"])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .spawn()
            .ok();
    }

    mpv::spawn(wall)?;
    let up = mpv::wait_socket(6000);
    if up {
        // let the first frames decode before dropping the swaybg fallback
        thread::sleep(Duration::from_millis(800));
    }
    if let Some(mut child) = swaybg.take() {
        let _ = child.kill();
        let _ = child.wait();
    }
    Ok(up)
}

/// Apply a theme everywhere. Writes config files + icons first (atomic),
/// then signals live processes, then switches the wallpaper via IPC when
/// possible. Frame generation runs detached and never blocks.
pub fn apply(wall: &str, pal: &Palette) -> Result<SyncReport, String> {
    write_active_palette(pal)?;
    write_kitty(pal, wall)?;
    write_waybar(pal)?;
    write_hypr_colors(pal)?;
    write_hyprlock_colors(pal)?;
    write_wofi_style(pal)?;
    cava::write(pal).map_err(|e| format!("cava: {}", e))?;

    let icons = match icons::sync(pal) {
        Ok(n) => n,
        Err(e) => return Err(format!("ikon motoru: {}", e)),
    };

    frames::link_lock_image(wall);

    let in_hypr = hypr::running();
    let wall_path = paths::wall_dir().join(wall).to_string_lossy().into_owned();
    let (ipc, started) = if !in_hypr {
        (false, false)
    } else if mpv::available() && mpv::loadfile(&wall_path) {
        (true, false)
    } else {
        (false, respawn_wallpaper(wall)?)
    };

    let kitty_live = live_kitty();
    signal("cava", "USR1");
    hypr::apply_border(pal);
    if in_hypr {
        daemon::recompute();
        // full reload: picks up recolored SVGs, dock.jsonc and palette css
        signal("waybar", "USR2");
    }

    frames::ensure_all_background(wall);

    Ok(SyncReport {
        wallpaper_ipc: ipc,
        wallpaper_started: started,
        hyprland: in_hypr,
        kitty_live,
        icons,
    })
}
